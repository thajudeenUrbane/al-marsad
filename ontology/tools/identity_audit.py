#!/usr/bin/env python3
"""
Identity audit: checks the Turtle files against ontology/corpus/identity.csv.

    .venv/bin/python ontology/tools/identity_audit.py            # run the checks, print a short report
    .venv/bin/python ontology/tools/identity_audit.py --check    # same checks, one line on success; exit 1 on any failure

History. Slice 1a made this script DERIVE identity.csv from the three Turtle
files and stories-50/data.json (it is still in git: commit d892992). Slice 1b
rewrote the Turtle onto the canonical IDs and applied the maintainer's
decisions by hand in the table, so the table is now the maintained source of
truth and this script only CHECKS it. It writes nothing.

The table: one row per entity (person, place, event, group). canonical_id is the
only ID that may appear in a .ttl file. variant_ids lists IDs that used to name
the same entity; they must appear in no .ttl file (rewrite by looking them up
here, never by trimming or fuzzy-matching IDs: IDs a character apart are often
different people). confidence: exact / probable / needs-review (see docs/handover/slice-1a.md).

Checks:
  1. columns, kinds, confidence values, ID prefixes agree with the row kind
  2. every ID (canonical or variant) appears in exactly one row
  3. every person/place/event/group IRI used in the Turtle files (the three originals plus stories-50.ttl) is a canonical_id
  4. no variant ID appears anywhere in the raw text of those Turtle files
  5. each canonical_id's source_files list matches the Turtle files that use it
  6. every stories-50 person (data.json) belongs to exactly one person row
New IDs come from ontology/tools/mint_id.py.
"""

import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import rdflib
from rdflib import URIRef

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "ontology" / "corpus" / "identity.csv"
STORIES = ROOT / "stories-50" / "data.json"
FILES = {
    "thawr": ROOT / "ontology" / "examples" / "thawr.ttl",
    "generation-1": ROOT / "ontology" / "corpus" / "generation-1.ttl",
    "seed-incidents": ROOT / "ontology" / "corpus" / "seed-incidents.ttl",
    "stories-50": ROOT / "ontology" / "corpus" / "stories-50.ttl",  # slice 1c, generated by stories50_to_ttl.py
}
BASE = "https://w3id.org/marsad/id/"
SEGMENT = {"person": "per", "place": "plc", "event": "ev", "group": "grp"}  # kind -> prefix (and IRI path segment: see below)
IRI_SEGMENT = {"per": "person", "plc": "place", "ev": "event", "grp": "group"}
COLUMNS = ["kind", "canonical_id", "preferred_name_en", "name_ar", "variant_ids",
           "stories50_names", "source_files", "confidence", "note"]
CONFIDENCE = {"exact", "probable", "needs-review"}


def curie(iri):
    seg, payload = str(iri)[len(BASE):].split("/", 1)
    return f"{[p for p, s in IRI_SEGMENT.items() if s == seg][0]}:{payload}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="quiet; exit 1 on any failure")
    args = ap.parse_args()
    errors = []

    with TABLE.open(encoding="utf-8", newline="") as fh:
        rd = csv.DictReader(fh)
        if rd.fieldnames != COLUMNS:
            sys.exit(f"identity.csv columns are {rd.fieldnames}, expected {COLUMNS}")
        rows = list(rd)

    # 1. shape of each row
    owner = {}
    variants = {}
    for r in rows:
        prefix = r["canonical_id"].split(":")[0]
        if SEGMENT.get(r["kind"]) != prefix:
            errors.append(f"{r['canonical_id']}: kind {r['kind']} does not match prefix {prefix}")
        if r["confidence"] not in CONFIDENCE:
            errors.append(f"{r['canonical_id']}: unknown confidence {r['confidence']!r}")
        ids = [r["canonical_id"]] + [v for v in r["variant_ids"].split(";") if v]
        for i in ids:
            if not re.fullmatch(r"(per|plc|ev|grp):[A-Za-z0-9]+", i):
                errors.append(f"malformed ID {i}")
            if i in owner:  # 2. one row per ID
                errors.append(f"{i} appears in two rows: {owner[i]} and {r['canonical_id']}")
            owner[i] = r["canonical_id"]
        for v in ids[1:]:
            variants[v] = r["canonical_id"]
    canonical = {r["canonical_id"]: r for r in rows}

    # 3 + 4. Turtle IRIs and raw text
    used = defaultdict(set)  # canonical id -> files
    for name, path in FILES.items():
        g = rdflib.Graph()
        g.parse(path, format="turtle")
        for s, p, o in g:
            for x in (s, o):
                if isinstance(x, URIRef) and str(x).startswith(BASE):
                    seg = str(x)[len(BASE):].split("/", 1)[0]
                    if seg not in IRI_SEGMENT.values() or seg not in ("person", "place", "event", "group"):
                        continue  # report, assertion, chain ... IDs are not entities in this table
                    c = curie(x)
                    if c in variants:
                        errors.append(f"{name}: uses variant {c}, canonical is {variants[c]}")
                    elif c not in canonical:
                        errors.append(f"{name}: {c} is not in identity.csv")
                    else:
                        used[c].add(name)
        raw = path.read_text(encoding="utf-8")
        for v, canon in variants.items():
            pre, payload = v.split(":")
            seg = IRI_SEGMENT[pre]
            pats = (rf"(?<![A-Za-z0-9_:]){pre}:{payload}(?![A-Za-z0-9])",
                    rf"{re.escape(BASE)}{seg}/{payload}(?![A-Za-z0-9])")
            if any(re.search(p, raw) for p in pats):
                errors.append(f"{name}: raw text still contains variant {v} (canonical {canon})")

    # 5. source_files vs. use
    for c, r in canonical.items():
        listed = {f for f in r["source_files"].split(";") if f in FILES}
        if listed != used.get(c, set()):
            errors.append(f"{c}: source_files says {sorted(listed)} but the Turtle files using it are {sorted(used.get(c, []))}")

    # 6. stories-50 people
    data = json.loads(STORIES.read_text(encoding="utf-8"))
    hits = defaultdict(list)
    for r in rows:
        if r["kind"] == "person":
            for n in r["stories50_names"].split(";"):
                hits[n].append(r["canonical_id"])
    for p in data["people"]:
        owners = set(hits.get(p["name"], []))
        if len(owners) != 1:
            errors.append(f"stories-50 person {p['name']!r} is in {len(owners)} person rows")

    if errors:
        print(f"identity audit FAILED, {len(errors)} problem(s):")
        for e in errors[:40]:
            print("  -", e)
        sys.exit(1)

    if args.check:
        print("identity audit passed")
        return
    by_kind = defaultdict(int)
    by_conf = defaultdict(int)
    for r in rows:
        by_kind[r["kind"]] += 1
        by_conf[r["confidence"]] += 1
    cross = defaultdict(set)
    for i in owner:
        cross[i.split(":")[1]].add(i.split(":")[0])
    print(f"rows: {len(rows)} (" + ", ".join(f"{k} {by_kind[k]}" for k in SEGMENT) + ")")
    print("confidence: " + ", ".join(f"{k} {by_conf[k]}" for k in sorted(CONFIDENCE)))
    print(f"variant IDs (must not appear in any .ttl): {len(variants)}")
    print(f"entity IRIs in the four Turtle files, all canonical: {len(used)}")
    print(f"payloads shared across kinds (recorded, not renamed): {sum(1 for v in cross.values() if len(v) > 1)}")
    print("identity audit passed")


if __name__ == "__main__":
    main()
